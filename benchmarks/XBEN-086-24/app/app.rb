require 'sinatra'
require 'erb'
require 'json'
require 'securerandom'

set :bind, '0.0.0.0'
set :show_exceptions, false

# In-memory storage for generated configurations
$configurations = {}

# Vulnerable: Does NOT escape #{} interpolation sequences
# This mimics the CVE where only partial escaping was done (quotes but not code)
# The generated code uses double-quoted strings, so #{} will be evaluated during eval()
def escape_for_code(input)
  # Only basic sanitization - doesn't prevent code injection!
  # We don't escape #{} which is the vulnerability
  input.to_s
end

# Simulated "client wrapper code generation" - like the CVE's buildClientWrapperCode
# Vulnerability: User input containing #{} gets executed when the code is eval'd
# because we use double-quoted strings in the generated code
def build_client_wrapper_code(server, path, port)
  # Only escape double quotes - #{} sequences pass through unmodified!
  escaped_server = escape_for_code(server)
  escaped_path = escape_for_code(path)
  
  # Generate Ruby code using %Q{} - user's #{} will be in the output
  # When this code is later eval'd, the #{} gets executed!
  code = %Q{# Auto-generated RPC Client Configuration
# Generated by ConfigGen Studio v2.3.1

module RPCClient
  class Client
    attr_accessor :server, :path, :port, :timeout
    
    def initialize
      @server = "#{escaped_server}"
      @path = "#{escaped_path}"
      @port = #{port.to_i}
      @timeout = 30
    end
    
    def connect
      puts "Connecting to " + @server + ":" + @port.to_s + @path
    end
    
    def server_info
      @server
    end
  end
end

# Create and return client instance
client = RPCClient::Client.new
client.server_info
}
  
  code
end

# Preview function that actually evaluates the code (dangerous!)
def preview_client_code(code)
  begin
    eval(code)
  rescue => e
    "Error evaluating code: #{e.message}"
  end
end

get '/' do
  erb :index
end

get '/status' do
  content_type :json
  { status: 'online', version: '2.3.1', service: 'ConfigGen Studio' }.to_json
end

# Documentation page
get '/docs' do
  erb :docs
end

# About page
get '/about' do
  erb :about
end

# API info endpoint
get '/api/info' do
  content_type :json
  {
    api_version: '1.0',
    endpoints: [
      { path: '/generate', method: 'POST', description: 'Generate client configuration code' },
      { path: '/preview', method: 'POST', description: 'Preview generated code' },
      { path: '/api/templates', method: 'GET', description: 'List available templates' },
      { path: '/api/validate', method: 'POST', description: 'Validate configuration parameters' }
    ]
  }.to_json
end

# Templates endpoint
get '/api/templates' do
  content_type :json
  {
    templates: [
      { id: 'rpc_basic', name: 'Basic RPC Client', description: 'Simple RPC client configuration' },
      { id: 'rpc_secure', name: 'Secure RPC Client', description: 'RPC client with TLS support' },
      { id: 'rpc_async', name: 'Async RPC Client', description: 'Asynchronous RPC client' }
    ]
  }.to_json
end

# Validation endpoint (non-vulnerable)
post '/api/validate' do
  content_type :json
  server = params[:server] || ''
  path = params[:path] || ''
  port = params[:port] || '80'
  
  errors = []
  errors << 'Server is required' if server.empty?
  errors << 'Path must start with /' unless path.start_with?('/')
  errors << 'Port must be numeric' unless port.to_s.match?(/^\d+$/)
  
  if errors.empty?
    { valid: true, message: 'Configuration is valid' }.to_json
  else
    status 400
    { valid: false, errors: errors }.to_json
  end
end

# Main code generation endpoint
post '/generate' do
  server = params[:server] || 'localhost'
  path = params[:path] || '/rpc'
  port = params[:port] || '80'
  template = params[:template] || 'rpc_basic'
  
  @server = server
  @path = path  
  @port = port
  @template = template
  
  # Generate the code
  @generated_code = build_client_wrapper_code(server, path, port)
  
  # Store for later preview
  config_id = SecureRandom.hex(8)
  $configurations[config_id] = @generated_code
  @config_id = config_id
  
  erb :result
end

# Preview endpoint - evaluates the generated code (VULNERABLE!)
post '/preview' do
  content_type :json
  
  config_id = params[:config_id]
  code = params[:code]
  
  # Either use stored config or provided code
  if config_id && $configurations[config_id]
    code = $configurations[config_id]
  elsif code.nil? || code.empty?
    status 400
    return { error: 'No code provided for preview' }.to_json
  end
  
  # Execute the code to preview the result - THIS IS THE SINK!
  result = preview_client_code(code)
  
  { 
    status: 'executed',
    result: result.to_s,
    message: 'Code preview completed'
  }.to_json
end

# Debugger endpoint - combines generate + execute (VULNERABLE!)
post '/debugger/execute' do
  content_type :json
  
  server = params[:server]
  path = params[:path]
  port = params[:port] || '80'
  
  if server.nil? || server.empty?
    status 400
    return { error: 'Server address is required' }.to_json
  end
  
  # Generate and immediately execute
  code = build_client_wrapper_code(server, path || '/rpc', port)
  result = preview_client_code(code)
  
  {
    status: 'executed',
    generated_code: code,
    execution_result: result.to_s
  }.to_json
end

error do
  content_type :json
  { error: 'Internal server error', message: env['sinatra.error'].message }.to_json
end

__END__

