        <h1>Welcome to OpenKnowledge</h1>
        <h2>Collaborative Documentation Platform</h2>
        <p>
        OpenKnowledge is a powerful wiki platform designed for teams who need to collaborate on documentation, knowledge bases, and internal wikis. Built with simplicity and flexibility in mind, it allows organizations to create, edit, and manage content with ease.
        </p>
        
        <h3>Key Features</h3>
        <ul>
            <li><strong>Customizable Themes:</strong> Choose from multiple themes or create your own with our flexible template system (squelettes)</li>
            <li><strong>Real-time Collaboration:</strong> Multiple users can edit and contribute simultaneously</li>
            <li><strong>Version Control:</strong> Track all changes and revert to previous versions when needed</li>
            <li><strong>Access Control:</strong> Fine-grained permissions for pages and sections</li>
            <li><strong>Plugin System:</strong> Extend functionality with community plugins</li>
        </ul>
        
        <h3>Getting Started</h3>
        <p>
        Visit the <a href="/wiki.php">Wiki</a> to start browsing and editing content. The wiki supports customizable themes through URL parameters - try adding <code>?theme=classic</code> to any wiki page to see a different look.
        </p>
        
        <h3>For Administrators</h3>
        <p>
        OpenKnowledge provides extensive customization options. Templates (called "squelettes" in the theming system) control the page layout and can be customized per-page. The theme system allows loading custom CSS and JavaScript to match your organization's branding.
        </p>
        <p>
        Check the <a href="/wiki.php?page=ThemeCustomization">Theme Customization</a> documentation for more details on available parameters.
        </p>
