        <h1>About OpenKnowledge</h1>
        <p>
        OpenKnowledge is an open-source wiki platform designed for collaborative documentation and knowledge management. Our mission is to make knowledge sharing simple, accessible, and powerful for teams of all sizes.
        </p>
        
        <h3>History</h3>
        <p>
        OpenKnowledge was created in 2018 as a fork of a popular wiki system, with a focus on improving the theming system and user experience. Since then, it has grown into a full-featured platform used by thousands of organizations worldwide.
        </p>
        
        <h3>Technology</h3>
        <p>
        Built on PHP with a modular architecture, OpenKnowledge features:
        </p>
        <ul>
            <li>Flexible template system (squelettes) for complete layout control</li>
            <li>Theme support with CSS and JavaScript customization</li>
            <li>RESTful API for integration with other tools</li>
            <li>Plugin architecture for extensibility</li>
            <li>Multi-language support</li>
        </ul>
        
